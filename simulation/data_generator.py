"""Synthetic dataset generation (Phase 1 deliverable).

For each simulated day this module:

1. draws a scenario (normal / peak_demand / disruption),
2. generates passenger demand and required trains per interval,
3. generates the fleet (readiness, maintenance, priority, depot berth) and the
   planned induction schedule,
4. runs :class:`MetroEnvironment` for the full operating day,
5. audits every track/platform occupancy log for conflicts and headway
   violations (generation aborts if any are found), and
6. aggregates the logs into CSV tables.

THE OUTPUT IS SYNTHETIC. It is not, and must not be presented as, Kochi Metro
Rail Limited (KMRL) operational data.

Determinism: one master seed -> ``numpy.random.SeedSequence`` -> independent
streams per day and per purpose. No global random state, no wall-clock time
and no unordered-set iteration is used, so identical seeds produce
byte-identical CSV files.
"""

from __future__ import annotations

import hashlib
import json
import logging
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from .config import seconds_to_clock
from .demand_generator import DemandGenerator
from .exceptions import MetroSchedError
from .metro_environment import MetroEnvironment, SimulationResult
from .scenario_generator import Scenario, ScenarioGenerator, assign_scheduled_inductions, generate_fleet
from .track import OccupancyRecord, audit_occupancy

logger = logging.getLogger(__name__)

SYNTHETIC_NOTICE = ("SYNTHETIC DATA generated by MetroSched for research/demonstration. "
                    "NOT actual Kochi Metro Rail Limited (KMRL) operational data.")

OUTPUT_FILES = [
    "scenarios.csv", "passenger_demand.csv", "train_readiness.csv", "train_availability.csv",
    "fleet_status_by_interval.csv", "induction_windows.csv", "track_availability.csv",
    "maintenance_events.csv", "operational_delays.csv", "platform_occupancy.csv",
    "induction_history.csv", "track_occupancy_log.csv",
]


class DataGenerationError(MetroSchedError):
    """Raised when generated data fails validation (e.g. a safety audit)."""


# ------------------------------------------------------------------ helpers
def overlap_seconds(starts: np.ndarray, step: int, spans: list[tuple[int, int]]) -> np.ndarray:
    """Seconds of each interval [s, s+step) covered by the union-free list of spans."""
    out = np.zeros(len(starts), dtype=np.int64)
    ends = starts + step
    for a, b in spans:
        out += np.clip(np.minimum(ends, b) - np.maximum(starts, a), 0, None)
    return out


def add_clock_columns(df: pd.DataFrame) -> pd.DataFrame:
    """For every ``*_time_s`` column add a human readable ``*_time`` (HH:MM:SS) column."""
    df = df.copy()
    durations = {"min_prep_time_s"}  # durations, not clock times
    for col in [c for c in df.columns if c.endswith("_time_s") and c not in durations]:
        df[col[:-2]] = df[col].map(lambda v: seconds_to_clock(v) if pd.notna(v) else "")
    return df


def audit_result(env: MetroEnvironment) -> list[dict]:
    """Audit every section of a finished simulation for safety violations."""
    violations = []
    for sid, sec in env.sections.items():
        recs = [OccupancyRecord(r.section_id, r.train_id, r.start, r.end, r.purpose) for r in sec.log]
        for v in audit_occupancy(recs, sec.headway_s, sec.closures):
            v["day"] = env.scenario.day
            violations.append(v)
    return violations


# ---------------------------------------------------------------- one day
def build_environment(cfg: dict, scenario: Scenario, control: str = "internal", dispatch_policy=None,
                      policy_name: str = "readiness_order"):
    """Build demand, fleet, plan and a ready-to-run MetroEnvironment for one day.

    The same scenario always yields the same demand, fleet and random events,
    whatever scheduler is then used -> fair, identical operating conditions.
    Returns (env, demand_df, readiness_records, plan, prep_delays).
    """
    seqs = np.random.SeedSequence(scenario.seed).spawn(3)
    demand_rng, fleet_rng, sim_rng = (np.random.default_rng(s) for s in seqs)
    demand = DemandGenerator(cfg).generate(demand_rng, scenario.weekday, scenario.demand_multiplier,
                                           day=scenario.day)
    trains, prep_delays = generate_fleet(cfg, scenario, fleet_rng)
    plan = assign_scheduled_inductions(trains, demand, cfg)
    readiness = [t.to_record() for t in trains]
    env = MetroEnvironment(cfg, scenario, demand, trains, sim_rng, dispatch_policy, policy_name,
                           control=control)
    return env, demand, readiness, plan, prep_delays


def simulate_day(cfg: dict, scenario: Scenario, dispatch_policy=None, policy_name="readiness_order"):
    """Run one operating day. Returns (demand_df, trains_before, plan, prep_delays, env, result)."""
    env, demand, readiness, plan, prep_delays = build_environment(cfg, scenario, "internal",
                                                                  dispatch_policy, policy_name)
    result = env.run()
    return demand, readiness, plan, prep_delays, env, result


def _aggregate_day(cfg: dict, scenario: Scenario, demand: pd.DataFrame, readiness: list[dict],
                   prep_delays: list[dict], env: MetroEnvironment, res: SimulationResult) -> dict:
    day = scenario.day
    step = int(cfg["simulation"]["interval_s"])
    starts = demand["interval_start_s"].to_numpy(dtype=np.int64)
    tables: dict[str, pd.DataFrame] = {}

    sc = scenario.to_record()
    sc["synthetic"] = True
    tables["scenarios.csv"] = pd.DataFrame([sc])
    tables["passenger_demand.csv"] = demand

    rd = pd.DataFrame(readiness)
    delay_map = {d["train_id"]: d["delay_s"] for d in prep_delays}
    rd.insert(0, "day", day)
    rd["prep_delay_s"] = rd["train_id"].map(delay_map).fillna(0).astype(int)
    rd = rd.drop(columns=["status", "location"])
    rd["initial_status"] = [r["status"] for r in readiness]
    tables["train_readiness.csv"] = add_clock_columns(rd)

    snaps = res.snapshots.copy()
    snaps.insert(0, "day", day)
    snaps["time"] = snaps["time_s"].map(seconds_to_clock)
    tables["train_availability.csv"] = snaps

    counts = (snaps.pivot_table(index="time_s", columns="status", values="train_id", aggfunc="count")
              .reindex(columns=cfg["fleet"]["states"]).fillna(0).astype(int).reset_index())
    counts.columns.name = None
    counts = counts.rename(columns={s: f"n_{s.lower()}" for s in cfg["fleet"]["states"]})
    counts = counts.merge(demand[["interval_start_s", "demand_pphpd", "required_trains"]],
                          left_on="time_s", right_on="interval_start_s", how="left").drop(columns="interval_start_s")
    on_line = snaps[snaps["location"] == "MAINLINE"].groupby("time_s")["train_id"].count()
    counts["in_service"] = on_line.reindex(counts["time_s"]).fillna(0).astype(int).to_numpy()
    counts["service_shortfall"] = (counts["required_trains"] - counts["in_service"]).clip(lower=0)
    counts.insert(0, "day", day)
    tables["fleet_status_by_interval.csv"] = counts

    win_rows = []
    for w in env.depot.windows:
        win_rows.append({"day": day, "window_id": w["id"], "start_time_s": w["start"], "end_time_s": w["end"],
                         "max_inductions": w["max_inductions"], "inductions_used": env.depot.window_counts[w["id"]],
                         "max_inductions_per_hour": env.depot.max_per_hour})
    tables["induction_windows.csv"] = add_clock_columns(pd.DataFrame(win_rows))

    occ = res.occupancy
    track_rows, pf_rows = [], []
    for sid, sec in env.sections.items():
        spans = []
        if not occ.empty:
            sub = occ[occ["section_id"] == sid]
            spans = list(zip(sub["start_s"].astype(int), sub["end_s"].astype(int)))
        entries = np.zeros(len(starts), dtype=int)
        for a, _ in spans:
            idx = int(np.searchsorted(starts, a, side="right") - 1)
            if 0 <= idx < len(starts):
                entries[idx] += 1
        occupied = overlap_seconds(starts, step, spans)
        closed = overlap_seconds(starts, step, sec.closures)
        avail = step - closed
        util = np.where(avail > 0, occupied / np.maximum(avail, 1), 0.0)
        for i, s in enumerate(starts):
            row = {"day": day, "interval_start_s": int(s), "interval_start": seconds_to_clock(s),
                   "occupied_s": int(occupied[i]), "closed_s": int(closed[i]),
                   "available_s": int(avail[i]), "utilization": round(float(util[i]), 4),
                   "train_entries": int(entries[i])}
            if sec.kind == "platform":
                pf_rows.append({"platform_id": sid, **row, "is_open": bool(closed[i] == 0)})
            else:
                track_rows.append({"section_id": sid, "section_kind": sec.kind,
                                   "headway_s": sec.headway_s, **row, "is_available": bool(closed[i] == 0)})
    tables["track_availability.csv"] = pd.DataFrame(track_rows)
    tables["platform_occupancy.csv"] = pd.DataFrame(pf_rows)

    me = res.maintenance_events.copy()
    if me.empty:
        me = pd.DataFrame(columns=["train_id", "event_type", "reason", "start_time_s",
                                   "planned_duration_s", "end_time_s"])
    me.insert(0, "day", day)
    tables["maintenance_events.csv"] = add_clock_columns(me)

    dl = res.delays.copy()
    prep = pd.DataFrame([{"train_id": d["train_id"], "delay_type": "preparation",
                          "start_time_s": d["prep_start_s"], "delay_s": d["delay_s"], "detail": ""}
                         for d in prep_delays], columns=dl.columns)
    dl = pd.concat([prep, dl], ignore_index=True) if not prep.empty else dl
    dl.insert(0, "day", day)
    tables["operational_delays.csv"] = add_clock_columns(dl)

    ih = res.inductions.copy()
    ih.insert(0, "day", day)
    ih.insert(1, "scenario_type", scenario.scenario_type)
    tables["induction_history.csv"] = add_clock_columns(ih)

    ol = occ.copy()
    ol.insert(0, "day", day)
    tables["track_occupancy_log.csv"] = ol
    return tables


# ------------------------------------------------------------ full dataset
def generate_dataset(cfg: dict, seed: int, n_days: int = 30, output_dir: str | Path | None = None,
                     start_weekday: int = 0, config_path: str | Path | None = None) -> dict:
    """Generate ``n_days`` of synthetic data and (optionally) write CSVs.

    Returns a dict of ``{file_name: DataFrame}`` plus a ``"manifest"`` entry.
    """
    if n_days < 30:
        logger.warning("Generating %d days; the project spec asks for at least 30", n_days)
    scenarios = ScenarioGenerator(cfg, seed).generate(n_days, start_weekday)
    per_file: dict[str, list[pd.DataFrame]] = {f: [] for f in OUTPUT_FILES}
    total_violations, summary = 0, []
    for sc in scenarios:
        demand, readiness, plan, prep, env, res = simulate_day(cfg, sc)
        violations = audit_result(env)
        if violations:
            total_violations += len(violations)
            raise DataGenerationError(f"Safety audit failed on day {sc.day}: {violations[:3]}")
        tables = _aggregate_day(cfg, sc, demand, readiness, prep, env, res)
        for name, df in tables.items():
            per_file[name].append(df)
        summary.append({"day": sc.day, "scenario": sc.scenario_type, "inductions": len(res.inductions),
                        "unfulfilled_requests": res.unfulfilled_requests})
        logger.info("Day %02d %-11s inductions=%3d delays=%3d maintenance=%2d unfulfilled=%d",
                    sc.day, sc.scenario_type, len(res.inductions), len(res.delays),
                    len(res.maintenance_events), res.unfulfilled_requests)

    data = {name: pd.concat([d for d in dfs if not d.empty], ignore_index=True) if any(not d.empty for d in dfs)
            else (dfs[0] if dfs else pd.DataFrame())
            for name, dfs in per_file.items()}

    cfg_hash = hashlib.sha256(yaml.safe_dump(cfg, sort_keys=True).encode()).hexdigest()[:16]
    manifest = {
        "notice": SYNTHETIC_NOTICE,
        "seed": int(seed), "n_days": int(n_days), "start_weekday": int(start_weekday),
        "fleet_size": int(cfg["fleet"]["size"]), "config_sha256_16": cfg_hash,
        "config_file": Path(config_path).name if config_path else "metro_config.yaml",
        "safety_violations": total_violations,
        "scenario_counts": {t: sum(s.scenario_type == t for s in scenarios)
                            for t in ["normal", "peak_demand", "disruption"]},
        "files": {name: int(len(df)) for name, df in data.items()},
    }
    if output_dir is not None:
        out = Path(output_dir)
        out.mkdir(parents=True, exist_ok=True)
        for name, df in data.items():
            path = out / name
            try:
                df.to_csv(path, index=False, lineterminator="\n")
            except OSError as exc:
                raise DataGenerationError(f"Could not write {path}: {exc}") from exc
        (out / "dataset_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
        (out / "README_SYNTHETIC_DATA.txt").write_text(SYNTHETIC_NOTICE + "\n", encoding="utf-8")
        logger.info("Wrote %d CSV files to %s", len(data), out)
    data["manifest"] = manifest
    data["summary"] = pd.DataFrame(summary)
    return data
